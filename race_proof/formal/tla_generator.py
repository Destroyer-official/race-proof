"""TLA+ Formal Specification Generator for Web API Concurrency Models.

Translates empirical RaceSession observations into a mathematically rigorous
TLA+ specification module suitable for model checking via TLC or Alloy.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from race_proof.models import RaceSession


@dataclass
class TlaModelSpec:
    module_name: str
    tla_source: str
    cfg_source: str
    num_threads: int
    initial_balance: int
    cost_per_action: int
    invariants: list[str]


class TlaSpecificationGenerator:
    """Generates TLA+ specification and TLC configuration from a RaceSession."""

    @classmethod
    def generate_spec(
        self,
        session: RaceSession,
        module_name: str = "WebApiRaceModel",
        initial_balance: int = 100,
        cost_per_action: int = 100,
    ) -> TlaModelSpec:
        num_threads = min(max(len(session.race_responses), 2), 6)  # Bound threads for tractable model checking
        threads_set = ", ".join(f"T{i}" for i in range(1, num_threads + 1))

        endpoint = (
            session.metadata.get("target_url")
            or (session.baseline.request.url if session.baseline.request else "unknown_endpoint")
        )
        tla_template = f"""---------------- MODULE {module_name} ----------------
EXTENDS Naturals, Sequences, FiniteSets, TLC

(*
 * Auto-generated by RaceProof 2027 Formal Verification Engine.
 * Source endpoint: {endpoint}
 * Modeled concurrent requests: {num_threads}
 *)

CONSTANTS 
    Threads,
    InitialBalance,
    CostPerAction

VARIABLES 
    balance,
    thread_pc,
    success_count

vars == <<balance, thread_pc, success_count>>

(* Thread states: IDLE -> READ_STATE -> COMMITTING -> DONE *)

Init ==
    /\\ balance = InitialBalance
    /\\ thread_pc = [t \\in Threads |-> "IDLE"]
    /\\ success_count = 0

(* Step 1: Thread reads balance snapshot without pessimistic lock *)
ReadAndCheck(t) ==
    /\\ thread_pc[t] = "IDLE"
    /\\ IF balance >= CostPerAction
       THEN thread_pc' = [thread_pc EXCEPT ![t] = "ELIGIBLE"]
       ELSE thread_pc' = [thread_pc EXCEPT ![t] = "REJECTED"]
    /\\ UNCHANGED <<balance, success_count>>

(* Step 2: Thread commits mutation based on stale snapshot *)
CommitMutate(t) ==
    /\\ thread_pc[t] = "ELIGIBLE"
    /\\ balance' = balance - CostPerAction
    /\\ success_count' = success_count + 1
    /\\ thread_pc' = [thread_pc EXCEPT ![t] = "DONE"]

(* Step 3: Rejected thread terminates cleanly *)
FailDone(t) ==
    /\\ thread_pc[t] = "REJECTED"
    /\\ thread_pc' = [thread_pc EXCEPT ![t] = "DONE"]
    /\\ UNCHANGED <<balance, success_count>>

Next ==
    \\E t \\in Threads :
        \\/ ReadAndCheck(t)
        \\/ CommitMutate(t)
        \\/ FailDone(t)

Spec == Init /\\ [][Next]_vars

(* Formal Invariants *)
NoOverdraft == balance >= 0
SingleWinner == success_count <= 1
TypeOK == 
    /\\ balance \\in Int
    /\\ success_count \\in 0..Cardinality(Threads)
    /\\ \\A t \\in Threads : thread_pc[t] \\in {{"IDLE", "ELIGIBLE", "REJECTED", "DONE"}}

=============================================================================
"""

        cfg_template = f"""SPECIFICATION Spec
CONSTANTS
    Threads = {{{threads_set}}}
    InitialBalance = {initial_balance}
    CostPerAction = {cost_per_action}

INVARIANTS
    NoOverdraft
    SingleWinner
    TypeOK
"""

        return TlaModelSpec(
            module_name=module_name,
            tla_source=tla_template,
            cfg_source=cfg_template,
            num_threads=num_threads,
            initial_balance=initial_balance,
            cost_per_action=cost_per_action,
            invariants=["NoOverdraft", "SingleWinner", "TypeOK"],
        )
