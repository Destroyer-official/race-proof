"""Automated PoC Generator.

Produces a standalone, executable asynchronous Python reproduction script
(`reproduce_race.py`) that uses `asyncio` and `httpx` with barrier synchronization
to replicate the exact race condition attack on demand.
"""
from __future__ import annotations

import json
from pathlib import Path
from race_proof.models import RaceSession, Verdict


class PocGenerator:
    """Generates an asynchronous Python reproduction PoC script."""

    @classmethod
    def generate(cls, session: RaceSession, verdict: Verdict) -> str:
        """Return the source code for reproduce_race.py."""
        target_url = "https://target.example.com/api"
        method = "POST"
        headers: dict[str, str] = {}
        body = ""

        # Extract representative request
        req = session.baseline.request or (
            session.race_responses[0].request if session.race_responses and session.race_responses[0].request else None
        )
        if req:
            target_url = req.url
            method = req.method
            headers = req.headers
            body = req.body or ""

        num_concurrent = len(session.race_responses)
        invariant_info = verdict.invariant_violated or "Single 200 Winner / Concurrency Integrity"

        template = f'''#!/usr/bin/env python3
"""
Automated Race Condition Reproduction Script
Generated by RaceProof v0.1.0

Finding ID: {verdict.finding_id}
Verdict: {verdict.verdict.value} (Confidence: {verdict.confidence:.1%})
Invariant: {invariant_info}
Target: {target_url}
"""

import asyncio
import time
import httpx

TARGET_URL = {target_url!r}
METHOD = {method!r}
CONCURRENT_REQUESTS = {num_concurrent}

HEADERS = {json.dumps(headers, indent=4)}
PAYLOAD = {json.dumps(body)}

async def send_worker(client: httpx.AsyncClient, barrier: asyncio.Barrier, index: int) -> dict:
    """Worker task that waits at the gate, then fires simultaneously."""
    await barrier.wait()  # Synchronize release
    t0 = time.perf_counter()
    try:
        if METHOD.upper() in ("POST", "PUT", "PATCH"):
            resp = await client.request(
                METHOD, TARGET_URL, headers=HEADERS, content=PAYLOAD, timeout=15.0
            )
        else:
            resp = await client.request(METHOD, TARGET_URL, headers=HEADERS, timeout=15.0)
        elapsed = (time.perf_counter() - t0) * 1000.0
        return {{
            "index": index,
            "status": resp.status_code,
            "elapsed_ms": round(elapsed, 2),
            "body": resp.text[:150],
        }}
    except Exception as exc:
        return {{"index": index, "status": 0, "error": str(exc)}}

async def main():
    print(f"[*] Firing {{CONCURRENT_REQUESTS}} simultaneous HTTP requests against: {{TARGET_URL}}")
    barrier = asyncio.Barrier(CONCURRENT_REQUESTS)
    
    # HTTP/2 multiplexing or HTTP/1.1 pool
    limits = httpx.Limits(max_connections=CONCURRENT_REQUESTS, max_keepalive_connections=CONCURRENT_REQUESTS)
    async with httpx.AsyncClient(limits=limits, http2=True, verify=False) as client:
        tasks = [
            asyncio.create_task(send_worker(client, barrier, i))
            for i in range(CONCURRENT_REQUESTS)
        ]
        results = await asyncio.gather(*tasks)

    print("\\n[+] Results:")
    print("-" * 65)
    print(f"{{'ID':<4}} | {{'STATUS':<8}} | {{'TIME (ms)':<10}} | {{'BODY PREVIEW'}}")
    print("-" * 65)
    for r in results:
        status_str = str(r.get("status", "ERR"))
        time_str = f"{{r.get('elapsed_ms', 0):.1f}} ms"
        preview = r.get("body", r.get("error", ""))[:40].replace("\\n", " ")
        print(f"{{r['index']:<4}} | {{status_str:<8}} | {{time_str:<10}} | {{preview}}")
    print("-" * 65)

if __name__ == "__main__":
    asyncio.run(main())
'''
        return template

